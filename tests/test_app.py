os.environ["USE_MONGOMOCK"] = "1"
os.environ.setdefault("URL_API", "http://www.omdbapi.com/?apikey=test")

import pytest  # noqa: E402

import db  # noqa: E402
from app import create_app  # noqa: E402


# A "fixture" is setup code pytest runs before each test that asks for it.
# Any test with a `client` parameter gets a fresh app and an empty fake database.
@pytest.fixture
def client():
    database = db.get_db()
    database.users.delete_many({})
    database.movies.delete_many({})
    app = create_app()
    app.testing = True
    return app.test_client()


def signup_and_login(client, username="alice", password="pw"):
    client.post("/user/signup", data={"username": username, "password": password})
    return client.post("/user/login", data={"username": username, "password": password})


def test_requires_login(client):
    r = client.get("/movies/")
    assert r.status_code == 302 and r.headers["Location"].endswith("/user/signup")


def test_signup_login_and_bad_password(client):
    r = signup_and_login(client)
    assert r.headers["Location"].endswith("/movies/")
    r = client.post("/user/login", data={"username": "alice", "password": "nope"})
    assert r.status_code == 401 and b"Invalid username or password" in r.data


def test_bcryptjs_hash_compatible(client):
    # hash of "secret" generated by Node's bcryptjs ($2a$ prefix)
    import bcrypt

    h = bcrypt.hashpw(b"secret", bcrypt.gensalt(10)).decode().replace("$2b$", "$2a$", 1)
    db.users().insert_one({"username": "legacy", "password": h})
    r = client.post("/user/login", data={"username": "legacy", "password": "secret"})
    assert r.status_code == 302


def test_full_movie_flow(client):
    signup_and_login(client)
    omdb = {"Title": "Jaws", "Year": "1975", "Released": "20 Jun 1975", "Actors": "Roy Scheider",
            "Plot": "Shark.", "Poster": "http://x/p.jpg", "Response": "True"}
    with patch("blueprints.movies.requests.get") as g:
        g.return_value.json.return_value = omdb
        r = client.post("/movies/results", data={"title": "Jaws", "year": ""})
        assert b"Jaws" in r.data and b"Add to my list" in r.data
        assert "t=jaws" in g.call_args[0][0]

    client.post("/movies/", data={"title": "Jaws", "year": "1975", "released": "20 Jun 1975",
                                  "actors": "Roy Scheider", "plot": "Shark.", "poster": "http://x/p.jpg",
                                  "watched": "2024-01-01"})
    movie = db.movies().find_one({"Title": "Jaws"})
    assert movie["username"] == "alice" and movie["Year"] == 1975

    r = client.get("/movies/")
    # the nice_date filter shows "2024-01-01" as "Jan 1, 2024"
    assert b"Jaws" in r.data and b"Watched Jan 1, 2024" in r.data

    r = client.get(f"/movies/{movie['_id']}")
    assert b"Save date" in r.data and b'value="2024-01-01"' in r.data

    client.post(f"/movies/{movie['_id']}?_method=PUT", data={"newwatched": "2025-05-05"})
    assert db.movies().find_one({"_id": movie["_id"]})["Watched"] == "2025-05-05"

    client.post(f"/movies/{movie['_id']}?_method=DELETE")
    assert db.movies().count_documents({}) == 0


def test_cannot_touch_other_users_movies(client):
    signup_and_login(client, "alice")
    mid = db.movies().insert_one({"Title": "Bob's", "username": "bob"}).inserted_id
    assert client.get(f"/movies/{mid}").status_code == 404
    client.post(f"/movies/{mid}?_method=DELETE")
    assert db.movies().count_documents({}) == 1


